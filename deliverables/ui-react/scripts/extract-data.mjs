// Extracts data literals from ../index.html (the HTML mock, kept in parallel)
// into src/data/generated.ts — guaranteeing data parity between mock and React app.
// Run from ui-react/:  node scripts/extract-data.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const mockPath = join(here, '..', '..', 'ui-mockup', 'index.html');
const outPath = join(here, '..', 'src', 'data', 'generated.ts');

const html = readFileSync(mockPath, 'utf8');
const lines = html.split('\n');

// Balanced-bracket scan: from the first opener after "const NAME =", walk to the
// matching closer, then expect the terminating ';'. String-literal aware.
function extract(name) {
  const decl = lines.findIndex(l => l.startsWith(`  const ${name} =`) || l.startsWith(`  let ${name} =`));
  if (decl === -1) throw new Error(`const ${name} not found`);
  let start = -1;
  const line = lines[decl];
  for (let i = 0; i < line.length; i++) {
    if (line[i] === '{' || line[i] === '[') { start = i; break; }
  }
  if (start === -1) {
    // scalar literal (string/number/boolean): take to the terminating ';'
    const parts = [];
    for (let li = decl; li < lines.length; li++) {
      const s = li === decl ? line.slice(line.indexOf('=') + 1) : lines[li];
      const semi = s.lastIndexOf(';');
      if (semi !== -1) { parts.push(s.slice(0, semi)); break; }
      parts.push(s);
    }
    return parts.join('\n').trim();
  }
  let depth = 0, inStr = null, endLine = decl, endCol = -1;
  outer:
  for (let li = decl; li < lines.length; li++) {
    const s = li === decl ? line.slice(start) : lines[li];
    for (let i = 0; i < s.length; i++) {
      const c = s[i], prev = s[i - 1];
      if (inStr) {
        if (c === inStr && prev !== '\\') inStr = null;
      } else if (c === '/' && s[i + 1] === '*') {
        const end = s.indexOf('*/', i + 2);
        if (end === -1) break;                      // comment continues on next line
        i = end + 1;                                // skip past '*/' (loop i++ lands after)
      } else if (c === '/' && s[i + 1] === '/') {
        break;                                      // line comment — rest of line ignored
      } else if (c === "'" || c === '"' || c === '`') {
        inStr = c;
      } else if (c === '{' || c === '[') depth++;
      else if (c === '}' || c === ']') {
        depth--;
        if (depth === 0) { endLine = li; endCol = i; break outer; }
      }
    }
  }
  if (endCol === -1) throw new Error(`unbalanced literal for ${name}`);
  const parts = [];
  for (let li = decl; li <= endLine; li++) {
    let s = lines[li];
    if (li === decl) s = s.slice(start);
    if (li === endLine) s = s.slice(0, endCol + 1);
    parts.push(s);
  }
  let lit = parts.join('\n');
  // TS safety: escape closing script sequences can't occur in data, but </script> could — guard
  lit = lit.replace(/<\/script>/gi, '<\\/script>');
  return lit;
}

const NAMES = [
  'PERSONA_LABEL', 'RBAC', 'TENANCY', 'CREDS', 'TEAM_HOME', 'ARCH_APP',
  'ARCH_LEVEL_LABEL', 'MODAL_VIEWS', 'APP_INCIDENTS', 'CMP_RUNS', 'CMP_ROWS',
  'PM_WAVE_WINDOWS', 'PM_WAVE_NARRATIVE', 'MOCK_APPS', 'MOCK_ARCHETYPES',
  'MOCK_BSVCS', 'FUNC_BY_TEAM_ROLE', 'STAKE_OVERRIDES', 'MOCK_WAVES',
  'MOCK_GROUPS', 'MOCK_FUNCTIONS', 'MOCK_TAGS', 'AUDIT_LOG', 'ACTIVE_LOGINS',
  'EXTRA_USERS', 'MOCK_PLATFORMS', 'MOCK_TARGETS', 'MOCK_IDENTITIES',
  'MOCK_GATEWAYS', 'MOCK_AGENTS', 'MOCK_SKILLS', 'MOCK_WORKFLOWS',
  'MOCK_WFRUNS', 'MOCK_AGENT_RUNS', 'AG_TABS', 'CFG_TABS', 'RHDS_ICONS', 'WAVE_EVIDENCE',
  'WAVE_TICKETS', 'WAVE_DEPS', 'MOCK_RUN_TREND', 'TEAM_ROLE_SECTIONS',
];

const chunks = [
  `/* GENERATED by scripts/extract-data.mjs — do not edit by hand.
   Source of truth: ui-mockup/index.html (kept in parallel per the migration plan).
   Entities (&middot; etc.) are preserved verbatim for render parity. */`,
];
for (const name of NAMES) {
  const lit = extract(name);
  chunks.push(`export const ${name} = ${lit};`);
}

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, chunks.join('\n\n') + '\n', 'utf8');
console.log(`extracted ${NAMES.length} literals -> ${outPath} (${(chunks.join('\n').length / 1024).toFixed(0)} kB)`);
